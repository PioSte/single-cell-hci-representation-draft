def _(fusion, go, make_set, mo, np, select_channels, torch):
    base = make_set(60, seed=7)
    fused_means = []
    with torch.no_grad():
        for c in range(1, 41):
            sub = select_channels(base, torch.arange(60) < c)
            fused, _ = fusion(sub)
            fused_means.append(fused.mean(dim=1).squeeze(0))
