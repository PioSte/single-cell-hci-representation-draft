@app.cell
def _(mo, torch):
    def structured_batch(B, seed, H=16, c_min=2, c_max=5, n_channel_ids=16):
        """Channels share a spatial latent (so imputation is learnable)."""
        g = torch.Generator().manual_seed(seed)
        k = torch.tensor([[1.0, 2, 1], [2, 4, 2], [1, 2, 1]]).view(1, 1, 3, 3)
        k = k / k.sum()
        imgs, ids = [], []
        for _ in range(B):
            c = int(torch.randint(c_min, c_max + 1, (1,), generator=g).item())
            z = torch.nn.functional.conv2d(
                torch.randn(1, 1, H, H, generator=g), k, padding=1
            )
            gain = torch.randn(c, 1, 1, 1, generator=g)
            bias = torch.randn(c, 1, 1, 1, generator=g)
            img = z * gain + bias + 0.1 * torch.randn(c, 1, H, H, generator=g)
            imgs.append(img)
            ids.append(torch.randperm(n_channel_ids, generator=g)[:c])
        return imgs, ids

    mae_steps = mo.ui.slider(50, 800, value=400, step=50, label="MAE training steps")
    mae_steps
    return mae_steps, structured_batch


@app.cell
def _(ChannelFusionMAE, mae_steps, mo, structured_batch, torch):
    torch.manual_seed(0)
    mae = ChannelFusionMAE(
        image_size=16,
        patch_size=8,
        dim=64,
        encoder_depth=2,
        decoder_depth=2,
        n_heads=4,
        n_memory=4,
        num_channel_ids=16,
    )
    train_imgs, train_ids = structured_batch(24, seed=1)
    opt = torch.optim.AdamW(mae.parameters(), lr=2e-3, weight_decay=0.01)
    losses = []
    mae.train()
    for step in range(int(mae_steps.value)):
        mae_out = mae(
            train_imgs, train_ids, generator=torch.Generator().manual_seed(step)
        )
        opt.zero_grad()
        mae_out["loss"].backward()
        opt.step()
        losses.append(mae_out["loss"].item())
    mo.md(
        f"Trained a tiny MAE for {int(mae_steps.value)} steps — "
        f"loss **{losses[0]:.3f} → {losses[-1]:.3f}** "
        f"(masked channel-patches are the supervision target)."
    )
    return losses, mae


