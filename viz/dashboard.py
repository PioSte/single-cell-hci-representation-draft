@app.cell
def _(ChannelSet, math, torch):
    DIM = 64
    NP = 4  # spatial patches per channel
    N_CHANNEL_IDS = 32

    def make_set(C, seed=0, include_identity=True, n_samples=1):
        """A full ``n_samples``-batch of ``C``-channel sets (canonical (c,n) order)."""
        g = torch.Generator().manual_seed(seed)
        tokens, si, ci, pi, cid, embed, cgid = [], [], [], [], [], [], []
        for b in range(n_samples):
            for c in range(C):
                channel_id = int(torch.randint(0, N_CHANNEL_IDS, (1,), generator=g).item())
                vec = torch.randn(DIM, generator=g)
                for n in range(NP):
                    tokens.append(torch.randn(DIM, generator=g) + vec)
                    si.append(b)
                    ci.append(c)
                    pi.append(n)
                    cid.append(channel_id)
                    embed.append(vec)
                    cgid.append(b * C + c)
        cs = ChannelSet(
            tokens=torch.stack(tokens),
            sample_idx=torch.tensor(si),
            channel_idx=torch.tensor(ci),
            patch_idx=torch.tensor(pi),
            channel_id=torch.tensor(cid),
            n_samples=n_samples,
            n_patches=NP,
            channel_embed=torch.stack(embed),
            channel_group_id=torch.tensor(cgid),
        )
        if not include_identity:
            cs.tokens = cs.tokens - cs.channel_embed
        return cs

    def permute_set(cs, seed=0):
        """True reordering of the channel *blocks* (rows shuffled)."""
        C = int(cs.channel_idx.max()) + 1
        n = cs.n_samples
        perm = torch.randperm(C, generator=torch.Generator().manual_seed(seed))
        idx = (perm.repeat_interleave(NP) * NP + torch.arange(NP).repeat(C)).repeat(n)
        # add per-sample offset
        off = torch.arange(n).repeat_interleave(C * NP) * (C * NP)
        idx = idx + off
        return ChannelSet(
            tokens=cs.tokens[idx],
            sample_idx=cs.sample_idx[idx],
            channel_idx=cs.channel_idx[idx],
            patch_idx=cs.patch_idx[idx],
            channel_id=cs.channel_id[idx],
            n_samples=cs.n_samples,
            n_patches=cs.n_patches,
            channel_embed=cs.channel_embed[idx],
            channel_group_id=cs.channel_group_id[idx],
        )

    def select_channels(cs, keep_mask):
        """Keep a subset of channel indices (per-channel boolean over 0..C-1)."""
        keep = keep_mask[cs.channel_idx]
        return ChannelSet(
            tokens=cs.tokens[keep],
            sample_idx=cs.sample_idx[keep],
            channel_idx=cs.channel_idx[keep],
            patch_idx=cs.patch_idx[keep],
            channel_id=cs.channel_id[keep],
            n_samples=cs.n_samples,
            n_patches=cs.n_patches,
            channel_embed=cs.channel_embed[keep],
            channel_group_id=cs.channel_group_id[keep],
        )

    @torch.no_grad()
    def attention_maps(fusion, cs):
        """Average attention over the channel axis, shape ``[N, C]``.

        Requires a single sample with a full ``(c, n)`` grid.
        """
        heads = fusion.n_heads
        dh = DIM // heads
        C = int(cs.channel_idx.max()) + 1
        tok = cs.tokens.reshape(C, NP, DIM)
        q = fusion.norm_q(fusion.queries).reshape(1, 1, heads, dh).expand(NP, 1, heads, dh)
        kv = fusion.norm_kv(tok).reshape(C, NP, heads, dh).permute(1, 2, 0, 3)
        qq = q.permute(0, 2, 1, 3)
        att = (qq @ kv.transpose(-1, -2)) / math.sqrt(dh)
        return att.softmax(-1).mean(dim=(1, 2)).detach()

    return DIM, NP, attention_maps, make_set, permute_set, select_channels


