@app.cell
def _(
    C,
    attention_maps,
    dense_fusion_reference,
    drop_slider,
    fusion,
    ident_check,
    make_set,
    permute_check,
    permute_set,
    select_channels,
    torch,
):
    cs_full = make_set(C, seed=7, include_identity=bool(ident_check.value))
    fused_full, present_full = fusion(cs_full)

    # padding-free vs masked-padded dense reference
    ref = dense_fusion_reference(fusion, cs_full)
    padfree_diff = (fused_full - ref).abs().max().item()

    # permutation invariance
    if permute_check.value and C > 1:
        cs_perm = permute_set(cs_full, seed=3)
        fused_perm, _ = fusion(cs_perm)
        perm_diff = (fused_full - fused_perm).abs().max().item()
    else:
        perm_diff = 0.0

    # omission: drop one channel and check it equals the omitted-set reference
    drop_idx = int(drop_slider.value)
    keep = torch.ones(C, dtype=torch.bool)
    if C > 1:
        keep[drop_idx] = False
    cs_drop = select_channels(cs_full, keep)
    fused_drop, _ = fusion(cs_drop)
    ref_drop = dense_fusion_reference(fusion, cs_drop)
    omission_diff = (fused_drop - ref_drop).abs().max().item()

    # identity ablation: same tokens, identity removed
    cs_noid = make_set(C, seed=7, include_identity=False)
    fused_noid, _ = fusion(cs_noid)
    identity_effect = (fused_full - fused_noid).abs().mean().item()

    att = attention_maps(fusion, cs_full)
    # spread of routing weights across channels (per location)
    routing_std = att.std(dim=1).mean().item()
    output_shape = tuple(fused_full.shape)
    return (
        att,
        identity_effect,
        omission_diff,
        output_shape,
        padfree_diff,
        perm_diff,
        routing_std,
    )


