@app.cell
def _(mae, np, plt, structured_batch, torch):
    test_imgs, test_ids = structured_batch(1, seed=999, c_min=5, c_max=5)
    Ctest = test_imgs[0].shape[0]
    visible = torch.ones(1, Ctest, 4, dtype=torch.bool)
    first_masked = min(2, Ctest - 1)
    visible[0, first_masked:, :] = False  # mask the tail channels entirely

    mae.eval()
    with torch.no_grad():
        recon = mae(test_imgs, test_ids, visible=visible)

    n_masked = Ctest - first_masked
    pred = recon["pred"].detach().reshape(n_masked, 4, 8, 8).numpy()  # [C, N, P, P]
    target = recon["target"].detach().reshape(n_masked, 4, 8, 8).numpy()

    def tile(patches):
        grid = np.zeros((16, 16))
        for i in range(2):
            for j in range(2):
                grid[i * 8 : (i + 1) * 8, j * 8 : (j + 1) * 8] = patches[i * 2 + j]
        return grid

    fig = plt.figure(figsize=(2.4 * n_masked, 4.6))
    for k in range(n_masked):
        ax = fig.add_subplot(2, n_masked, k + 1)
        ax.imshow(tile(target[k]), cmap="magma")
        ax.set_title(f"channel {first_masked + k}\nground truth", fontsize=9)
        ax.axis("off")
        ax = fig.add_subplot(2, n_masked, n_masked + k + 1)
        ax.imshow(tile(pred[k]), cmap="magma")
        ax.set_title("reconstruction", fontsize=9)
        ax.axis("off")
    fig.suptitle("Fully masked channels reconstructed from the remaining set", y=0.98)
    fig.tight_layout()

    return


